def seed_database():
    """Initializes tables and seeds the 30 demo medicines and initial reports."""
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        # Check if already seeded
        existing_count = db.query(Medicine).count()
        if existing_count >= len(SAMPLE_MEDICINES):
            print(f"Database already has {existing_count} medicines. Seed skipped.")
            return

        # Clear existing to ensure clean state
        db.query(CommunityReport).delete()
        db.query(Medicine).delete()
        db.commit()

        # Insert medicines
        for med_data in SAMPLE_MEDICINES:
            med = Medicine(**med_data)
            db.add(med)
        db.commit()
        print(f"Successfully seeded {len(SAMPLE_MEDICINES)} medicine records.")

        # Insert community demo reports
        report_total = 0
        now = datetime.now(timezone.utc)
        for rep in DEMO_REPORTS:
            for i in range(rep["count"]):
                # Distribute reported_at within past 1 to 5 days
                rep_item = CommunityReport(
                    batch_number=rep["batch_number"],
                    brand_name=rep["brand_name"],
                    manufacturer=rep["manufacturer"],
                    district=rep["district"],
                    note=rep["note"],
                    reported_at=now - timedelta(days=(i % 5), hours=(i * 3))
                )
                db.add(rep_item)
                report_total += 1
        db.commit()
        print(f"Successfully seeded {report_total} demo community reports.")

    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
